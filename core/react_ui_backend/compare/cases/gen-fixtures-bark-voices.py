import numpy as np, json, os, shutil
d=r"C:\scratch\routes-build\voices"; os.makedirs(d,exist_ok=True)
shutil.copy(r"C:\scratch\baseline\voices\Alice.npz", d+r"\Alice.npz")
tok=np.arange(10,dtype=np.int64)
def chars(s): return np.array(list(s))
def meta(n, uni=False):
    return chars(json.dumps({"prompt":"hello "+"x"*n,"language":"en","hash":"abc","date":"2024-01-01 00:00:00","note":"ünï名" if uni else "plain"}))
np.savez(d+r"\legacy-small.npz",tokens=tok,metadata=meta(5))
np.savez(d+r"\legacy-big.npz",tokens=tok,metadata=meta(900))
np.savez_compressed(d+r"\legacy-comp-big.npz",tokens=tok,metadata=meta(900,True))
np.savez_compressed(d+r"\legacy-comp-small.npz",tokens=tok,metadata=meta(5))
np.savez(d+r"\new-format.npz",tokens=tok,metadata=np.array(json.dumps({"a":1})))
np.savez(d+r"\nested-meta.npz",**{"a/metadata":chars('{"nested":true}')})
np.savez(d+r"\meta-array.npz",metadata=chars('[1,2,"x"]'))
np.savez(d+r"\meta-string.npz",metadata=chars('"hi"'))
np.savez(d+r"\meta-null.npz",metadata=chars('null'))
np.savez(d+r"\meta-number.npz",metadata=chars('5'))
np.savez(d+r"\meta-badjson.npz",metadata=chars('{not json'))
np.savez(d+r"\meta-filename.npz",metadata=chars('{"a":1,"filename":"zzz","url":"u","b":2}'))
np.savez(d+r"\meta-wide.npz",metadata=chars('{"e":"\U0001F600"}'))
np.savez(d+r"\meta-numkeys.npz",metadata=chars('{"b":1,"2":2,"1":3}'))
np.savez(d+r"\meta-u2.npz",metadata=np.array(["ab","cd"]))
np.savez(d+r"\meta-empty.npz",metadata=chars(''))
np.savez(d+r"\meta-dup.npz",metadata=chars('{"a":1,"a":2}'))
open(d+r"\not-zip.npz","wb").write(os.urandom(500))
open(d+r"\empty.npz","wb").write(b"")
shutil.copy(d+r"\legacy-small.npz", d+r"\UPPER.NPZ")
open(d+r"\notes.txt","w").write("x")
open(d+r"\a.npz.bak","w").write("x")
