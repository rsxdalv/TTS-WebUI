const B="----cmpBoundary123";
const part=(disp,data,ct)=>`--${B}\r\nContent-Disposition: ${disp}\r\n`+(ct?`Content-Type: ${ct}\r\n`:"")+`\r\n${data}\r\n`;
const file=(fname,data="DATA-"+fname,name="file")=>part(`form-data; name="${name}"; filename="${fname}"`,data,"application/octet-stream");
const str=(name,v)=>part(`form-data; name="${name}"`,v);
const end=`--${B}--\r\n`;
const mp=(...p)=>({ct:`multipart/form-data; boundary=${B}`,body:p.join("")+end});
const U="/api/upload";
const cases=[];
const add=(name,m,extra={})=>cases.push({name,method:"POST",path:U,header:{"Content-Type":[m.ct]},body:Buffer.from(m.body).toString("base64"),...extra});
add("normal wav",mp(file("t-normal.wav")));
add("upper ext",mp(file("t-upper.WAV")));
add("mp3",mp(file("t-a.mp3")));
add("npz",mp(file("t-a.npz")));
add("jpeg",mp(file("t-a.jpeg")));
add("traversal",mp(file("../../t-evil.wav")));
const BS=String.fromCharCode(92); add("traversal backslash",mp(file(".."+BS+".."+BS+"t-evil2.wav")));
add("abs unix",mp(file("/etc/t-abs.wav")));
add("abs windows",mp(file("C:"+BS+"x"+BS+"t-abs2.wav")));
add("drive no slash",mp(file("C:t-drive.wav")));
add("leading dots",mp(file("...t-dots.wav")));
add("only dots ext",mp(file("....wav")));
add("hidden",mp(file(".hidden.wav")));
add("exe",mp(file("t-bad.exe")));
add("no ext",mp(file("t-noext")));
add("double ext",mp(file("t-a.wav.exe")));
add("trailing dot",mp(file("t-a.wav.")));
add("trailing space",mp(file("t-a.wav ")));
add("empty filename",mp(file("")));
add("trailing slash",mp(file("t-dir.wav/")));
add("unicode",mp(file("t-ünï–名.wav")));
add("space",mp(file("t-a b.wav")));
add("quote",mp(file("t-q%22x.wav")));
add("zero byte",mp(file("t-zero.wav","")));
add("no file field",mp(str("other","x")));
add("file as string",mp(str("file","abc")));
add("file empty string",mp(str("file","")));
add("two files first wins",mp(file("t-first.wav"),file("t-second.wav")));
add("file after other",mp(str("a","b"),file("t-late.wav")));
add("string then file",mp(str("file","abc"),file("t-x.wav")));
add("file then string file",mp(file("t-y.wav"),str("file","abc")));
add("other field name file",mp(file("t-other.wav",undefined,"upload")));
cases.push({name:"empty multipart",method:"POST",path:U,header:{"Content-Type":[`multipart/form-data; boundary=${B}`]},body:Buffer.from(end).toString("base64")});
cases.push({name:"zero body multipart",method:"POST",path:U,header:{"Content-Type":[`multipart/form-data; boundary=${B}`]},body:""});
cases.push({name:"truncated",method:"POST",path:U,header:{"Content-Type":[`multipart/form-data; boundary=${B}`]},body:Buffer.from(file("t-trunc.wav")).toString("base64")});
cases.push({name:"no boundary",method:"POST",path:U,header:{"Content-Type":["multipart/form-data"]},body:Buffer.from(file("t-nb.wav")+end).toString("base64")});
cases.push({name:"json body",method:"POST",path:U,header:{"Content-Type":["application/json"]},body:Buffer.from('{"file":"x"}').toString("base64")});
cases.push({name:"no content type",method:"POST",path:U,body:Buffer.from("abc").toString("base64")});
cases.push({name:"urlencoded string file",method:"POST",path:U,header:{"Content-Type":["application/x-www-form-urlencoded"]},body:Buffer.from("file=abc").toString("base64")});
cases.push({name:"urlencoded empty file",method:"POST",path:U,header:{"Content-Type":["application/x-www-form-urlencoded"]},body:Buffer.from("file=").toString("base64")});
cases.push({name:"urlencoded no file",method:"POST",path:U,header:{"Content-Type":["application/x-www-form-urlencoded"]},body:Buffer.from("a=b").toString("base64")});
for (const m of ["GET","PUT","DELETE","HEAD"]) cases.push({name:"method "+m,method:m,path:U});
cases.push({name:"trailing slash",method:"POST",path:U+"/"});
require("fs").writeFileSync(process.argv[2],JSON.stringify(cases,null,1));
